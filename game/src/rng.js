// Deterministic randomness: one small PRNG, seeded per round and per screenshot,
// so a replay and a capture stage the same way. Nothing here touches Math.random
// during a round, which keeps the fixed-step simulation reproducible.
export function mulberry32(initial) {
  let a = initial | 0;
  return function random() {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function range(random, min, max) {
  return min + random() * (max - min);
}

export function pick(random, list) {
  return list[Math.floor(random() * list.length)];
}

export function shuffle(random, list) {
  const out = list.slice();
  for (let i = out.length - 1; i > 0; i -= 1) {
    const j = Math.floor(random() * (i + 1));
    const tmp = out[i];
    out[i] = out[j];
    out[j] = tmp;
  }
  return out;
}

// A cheap bell-ish spread for bot aim error: sum of two uniforms, centred on 0.
export function gauss(random, spread) {
  return (random() + random() + random() - 1.5) * spread;
}
